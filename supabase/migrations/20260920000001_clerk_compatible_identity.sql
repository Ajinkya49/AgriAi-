-- ---------------------------------------------------------------------------
-- 7. Verify
--
-- No policy may still call auth.uid(), or a Clerk user would raise on every
-- query. Failing loudly here is better than discovering it in production.
-- ---------------------------------------------------------------------------
do $$
declare
  remaining int;
begin
  select count(*) into remaining
  from pg_policies
  where schemaname = 'public'
    and (coalesce(qual, '') like '%auth.uid()%'
         or coalesce(with_check, '') like '%auth.uid()%');

  if remaining > 0 then
    raise exception
      'Clerk migration incomplete: % policy/policies still call auth.uid()',
      remaining;
  end if;
end $$;
