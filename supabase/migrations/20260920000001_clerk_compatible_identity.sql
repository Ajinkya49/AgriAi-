-- ===========================================================================
-- Clerk-compatible identity
--
-- Lets the schema accept a Clerk subject as well as a Supabase one, WITHOUT
-- breaking Supabase Auth. The app keeps working throughout — see
-- `docs/clerk-migration-assessment.md`.
--
-- Why this is needed: Supabase defines
--     auth.uid() -> coalesce(... ->> 'sub')::uuid
-- so it CASTS the JWT subject to uuid. Clerk subjects are strings
-- (`user_2abc...`), which makes every call site RAISE
-- `invalid input syntax for type uuid` — they do not merely mismatch.
--
-- The fix is a helper returning the raw subject as TEXT, with no cast, so it is
-- correct for both issuers:
--     Supabase -> 'a1b2c3d4-...'   (a uuid, as text)
--     Clerk    -> 'user_2abc...'
--
-- Generated by `supabase/scripts/generate_clerk_migration.py` from the deployed
-- policy definitions. Do not hand-edit the policy block.
--
-- DEPENDS ON: 20260915000003_rls_policies.sql
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. Identity helper — TEXT, no cast, issuer-agnostic
-- ---------------------------------------------------------------------------
create or replace function public.current_user_id()
returns text
language sql
stable
as $$
  select coalesce(
    nullif(current_setting('request.jwt.claim.sub', true), ''),
    (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub')
  );
$$;

comment on function public.current_user_id() is
  'JWT subject as TEXT, for either Supabase Auth (uuid) or Clerk (string). '
  'Prefer this over auth.uid(), which casts to uuid and therefore rejects a '
  'Clerk subject outright.';

revoke execute on function public.current_user_id() from public, anon;
grant execute on function public.current_user_id() to authenticated, service_role;

