-- ---------------------------------------------------------------------------
-- 3. Widen the identity columns to text
--
-- Three explicit phases, because the dependencies are circular:
--
--   * `users.id` cannot change type while a child FK still points at it
--   * a child `user_id` cannot change type while its FK still exists
--
-- So: drop every FK, alter every column, then recreate the FKs. Doing it
-- per-table (drop/alter/add, then next table) fails on the second table with
--     DETAIL: Key columns "user_id" and "id" are of incompatible types
-- because `users.id` is already text while that table's column is still uuid.
--
-- The FK to auth.users is dropped for good: with Clerk there IS no auth.users
-- row — Clerk is the identity system and Supabase's auth schema stays empty. The
-- FK would have no parent, and on_auth_user_created would never fire, so profile
-- rows have to be created by a Clerk webhook or a lazy upsert instead.
-- ---------------------------------------------------------------------------
alter table public.users drop constraint if exists users_id_fkey;

alter table public.assistant_conversations drop constraint if exists assistant_conversations_user_id_fkey;
alter table public.comments drop constraint if exists comments_user_id_fkey;
alter table public.communities drop constraint if exists communities_created_by_fkey;
alter table public.community_members drop constraint if exists community_members_user_id_fkey;
alter table public.diagnoses drop constraint if exists diagnoses_user_id_fkey;
alter table public.post_likes drop constraint if exists post_likes_user_id_fkey;
alter table public.posts drop constraint if exists posts_user_id_fkey;

alter table public.users alter column id type text;

comment on column public.users.id is
  'Identity subject: a Supabase uuid or a Clerk user id, as TEXT. No FK '
  'to auth.users — see the Clerk migration notes.';

alter table public.assistant_conversations alter column user_id type text;
alter table public.comments alter column user_id type text;
alter table public.communities alter column created_by type text;
alter table public.community_members alter column user_id type text;
alter table public.diagnoses alter column user_id type text;
