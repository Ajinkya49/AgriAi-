-- ---------------------------------------------------------------------------
-- 4. `public_profiles` — argument and return types widen with the column
--
-- It takes `uuid[]` and returns `id uuid`; both now disagree with
-- `public.users.id`. Left alone, every community feed read fails with
--     HINT: No operator matches the given name and argument types.
-- The body is unchanged — only the types move.
--
-- The narrow disclosure (id, name, role — never email, phone, region or crops)
-- is preserved exactly. See DECISIONS.md §7.1.
-- ---------------------------------------------------------------------------
drop function if exists public.public_profiles(uuid[]);

create or replace function public.public_profiles(user_ids text[])
returns table (
  id   text,
  name text,
  role text
)
language sql
security definer
stable
set search_path = public, pg_temp
as $$
  select u.id, u.name, u.role
  from public.users u
  where u.id = any(user_ids);
$$;

comment on function public.public_profiles(text[]) is
  'Public display fields (id, name, role) for community authors. Deliberately '
  'narrow: never expose email, phone, region or crops. See DECISIONS.md §7.1.';

revoke all on function public.public_profiles(text[]) from public;
revoke all on function public.public_profiles(text[]) from anon;
grant execute on function public.public_profiles(text[]) to authenticated;

-- ---------------------------------------------------------------------------
-- 5. Role helpers read the new identity function
-- ---------------------------------------------------------------------------
create or replace function public.current_app_role()
returns text
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select u.role from public.users u where u.id = public.current_user_id();
$$;

